"""Seeded repositories for the git-merge-and-conflict-resolution skill evals (specs/094 section 3.7, AC-7b).

Each `case_*` function builds a FRESH repository in the directory it is given, with plain git commands only.
The repo ends checked out on branch `feature`, which has diverged from `main` (or is only behind it, case e).
Nothing is merged: the builder meets the conflict by running `git merge main`. There is no remote.
The tips are recorded in `.git/eval-meta.json` (inside .git, so the work tree stays clean) for checks.py.
Stdlib only. Offline.
"""
import json
import os
import pathlib
import subprocess

ENV = {
    "GIT_AUTHOR_NAME": "Eval", "GIT_AUTHOR_EMAIL": "eval@example.invalid",
    "GIT_COMMITTER_NAME": "Eval", "GIT_COMMITTER_EMAIL": "eval@example.invalid",
    "GIT_AUTHOR_DATE": "2026-01-01T00:00:00Z", "GIT_COMMITTER_DATE": "2026-01-01T00:00:00Z",
    "GIT_CONFIG_GLOBAL": "/dev/null", "GIT_CONFIG_SYSTEM": "/dev/null", "GIT_CONFIG_NOSYSTEM": "1",
    "GIT_TERMINAL_PROMPT": "0", "GIT_EDITOR": "true", "GIT_MERGE_AUTOEDIT": "no",
}


def env():
    e = dict(os.environ)
    e.update(ENV)
    return e


def git(repo, *args, check=True):
    p = subprocess.run(["git", *args], cwd=str(repo), env=env(), capture_output=True, text=True, stdin=subprocess.DEVNULL)
    if check and p.returncode != 0:
        raise RuntimeError("git %s failed (%d): %s%s" % (" ".join(args), p.returncode, p.stdout, p.stderr))
    return p


def write(repo, name, text, mode=None):
    p = pathlib.Path(repo) / name
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)
    if mode:
        p.chmod(mode)


def commit(repo, msg, *names):
    git(repo, "add", *names) if names else git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", msg)


def head(repo, ref="HEAD"):
    return git(repo, "rev-parse", ref).stdout.strip()


def init(repo):
    pathlib.Path(repo).mkdir(parents=True, exist_ok=True)
    git(repo, "init", "-q", "-b", "main")
    git(repo, "config", "commit.gpgsign", "false")


def seal(repo, extra=None):
    """Record the tips; leave the repo on `feature`."""
    meta = {"main_tip": head(repo, "main"), "branch_tip": head(repo, "feature")}
    meta.update(extra or {})
    (pathlib.Path(repo) / ".git" / "eval-meta.json").write_text(json.dumps(meta))
    git(repo, "checkout", "-q", "feature")


def branch_point(repo, name="feature"):
    git(repo, "checkout", "-q", "-b", name)


def on_main(repo):
    git(repo, "checkout", "-q", "main")


# a) the spec tracker: both branches added a section and a table row at the very end -------------------------------

TRACKER_BASE = "# Tracker\n\nIntro.\n\n| id | state |\n| :-- | :-- |\n| 001 | done |\n"


def case_tracker(repo):
    init(repo)
    write(repo, "tracker.md", TRACKER_BASE)
    commit(repo, "base")
    branch_point(repo)
    write(repo, "tracker.md", TRACKER_BASE + "| 003 | draft |\n\n## Branch notes\nbranch section\n")
    commit(repo, "feature: add spec 003 and its notes")
    on_main(repo)
    write(repo, "tracker.md", TRACKER_BASE + "| 002 | approved |\n\n## Main notes\nmain section\n")
    commit(repo, "main: add spec 002 and its notes")
    seal(repo)


# b) a module list: both added a `mod` line (and its file) ------------------------------------------------------------

LIB_CHECK = """#!/bin/sh
# the gate: every module file is declared, every declaration has a file, no conflict markers
set -e
cd "$(dirname "$0")"
for f in *.rs; do
  n="${f%.rs}"
  [ "$n" = lib ] && continue
  grep -q "^mod $n;$" lib.rs || { echo "lib.rs does not declare mod $n"; exit 1; }
done
for n in $(sed -n 's/^mod \\([a-z_]*\\);$/\\1/p' lib.rs); do
  [ -f "$n.rs" ] || { echo "mod $n has no file"; exit 1; }
done
if grep -q '^<<<<<<<\\|^>>>>>>>' lib.rs; then echo "markers"; exit 1; fi
echo ok
"""


def case_modlist(repo):
    init(repo)
    write(repo, "lib.rs", "mod a;\nmod b;\n\npub fn f() {}\n")
    write(repo, "a.rs", "// a\n")
    write(repo, "b.rs", "// b\n")
    write(repo, "check.sh", LIB_CHECK, 0o755)
    commit(repo, "base")
    branch_point(repo)
    write(repo, "lib.rs", "mod a;\nmod b;\nmod y;\n\npub fn f() {}\n")
    write(repo, "y.rs", "// y\n")
    commit(repo, "feature: add mod y")
    on_main(repo)
    write(repo, "lib.rs", "mod a;\nmod b;\nmod x;\n\npub fn f() {}\n")
    write(repo, "x.rs", "// x\n")
    commit(repo, "main: add mod x")
    seal(repo)


# c) a generated file: out.md is `./gen.sh > out.md`; both sides edited items.txt and the generated out.md ---------

GEN_SH = """#!/bin/sh
# usage: ./gen.sh > out.md   (out.md is generated: never edit it by hand)
cd "$(dirname "$0")"
echo "<!-- generated by ./gen.sh > out.md -->"
echo "count: $(wc -l < items.txt | tr -d ' ')"
tr 'a-z' 'A-Z' < items.txt
"""


def gen_out(repo):
    return subprocess.run(["sh", "gen.sh"], cwd=str(repo), capture_output=True, text=True).stdout


def case_generated(repo):
    init(repo)
    write(repo, "gen.sh", GEN_SH, 0o755)
    write(repo, "items.txt", "alpha\nbeta\n")
    write(repo, ".gitattributes", "out.md linguist-generated=true\n")
    write(repo, "out.md", gen_out(repo))
    commit(repo, "base")
    branch_point(repo)
    write(repo, "items.txt", "alpha\nbeta\ndelta\nepsilon\n")
    write(repo, "out.md", gen_out(repo))
    commit(repo, "feature: add delta and epsilon, regenerate")
    on_main(repo)
    write(repo, "items.txt", "gamma\nalpha\nbeta\n")
    write(repo, "out.md", gen_out(repo))
    commit(repo, "main: add gamma, regenerate")
    seal(repo)


# d) a lockfile: the same package bumped differently; the right answer is the base's (main's) file ----------------

LOCK = '''# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "demo"
version = "0.1.0"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "%s"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "%s"
'''


def case_lockfile(repo):
    init(repo)
    write(repo, "Cargo.lock", LOCK % ("1.0.1", "a" * 64))
    write(repo, "Cargo.toml", '[package]\nname = "demo"\nversion = "0.1.0"\n')
    commit(repo, "base")
    branch_point(repo)
    write(repo, "Cargo.lock", LOCK % ("1.0.3", "c" * 64))
    write(repo, "notes.txt", "feature work\n")
    commit(repo, "feature: bump serde, add notes")
    on_main(repo)
    write(repo, "Cargo.lock", LOCK % ("1.0.2", "b" * 64))
    commit(repo, "main: bump serde")
    seal(repo)


# e) behind the base, no conflict ------------------------------------------------------------------------------------

def case_behind(repo):
    init(repo)
    write(repo, "one.txt", "one\n")
    commit(repo, "base")
    branch_point(repo)
    write(repo, "feature.txt", "feature\n")
    commit(repo, "feature: add feature.txt")
    write(repo, "feature.txt", "feature\nmore\n")
    commit(repo, "feature: extend feature.txt")
    on_main(repo)
    write(repo, "main.txt", "main\n")
    commit(repo, "main: add main.txt")
    seal(repo)


# f) semantic: the text merges cleanly, the gate then fails ----------------------------------------------------------
# Intent M (main):    the argument is now in DOLLARS (converted to cents inside).
# Intent B (feature): an order above 10000 CENTS ships free.
# Merged textually, B's test reads "$1" (now dollars), so 200 dollars is not free: check.sh fails.

RULE = """# shipping fee for an order
fee() {
  c=$1
  f=$(( c / 10 ))
  # fee is a tenth of the total
  #
  #
  echo "$f"
}
"""
RULE_CHECK = """#!/bin/sh
# the gate: both intents hold. The argument is dollars (M); above 10000 cents ships free (B).
cd "$(dirname "$0")"
. ./rule.sh
bad=0
t() { got=$(fee "$1"); [ "$got" = "$2" ] || { echo "fee $1 = $got, want $2"; bad=1; }; }
t 50 500
t 100 1000
t 101 0
t 200 0
exit $bad
"""


def case_semantic(repo):
    init(repo)
    write(repo, "rule.sh", RULE)
    write(repo, "check.sh", RULE_CHECK, 0o755)
    commit(repo, "base")
    branch_point(repo)
    write(repo, "rule.sh", RULE.replace('  echo "$f"\n', '  [ "$1" -gt 10000 ] && f=0\n  echo "$f"\n'))
    commit(repo, "feature: orders above 10000 cents ship free")
    on_main(repo)
    write(repo, "rule.sh", RULE.replace("  c=$1\n", "  c=$(( $1 * 100 ))   # the argument is now dollars\n"))
    commit(repo, "main: fee() takes dollars, not cents")
    seal(repo)


# name -> (builder function, task text handed to the builder)
CASES = {
    "tracker": (case_tracker, "Branch `feature` is behind `main`. Bring it up to date and resolve what conflicts. Do not push."),
    "modlist": (case_modlist, "Branch `feature` is behind `main`. Bring it up to date and resolve what conflicts. Run ./check.sh. Do not push."),
    "generated": (case_generated, "Branch `feature` is behind `main`. Bring it up to date and resolve what conflicts. out.md is generated by ./gen.sh. Do not push."),
    "lockfile": (case_lockfile, "Branch `feature` is behind `main`. Bring it up to date and resolve what conflicts. Do not push."),
    "behind": (case_behind, "Branch `feature` is behind `main`. Bring it up to date. Do not push."),
    "semantic": (case_semantic, "Branch `feature` is behind `main`. Bring it up to date and make sure ./check.sh passes. If you cannot, leave a file NEEDS-HUMAN saying why. Do not push."),
}


def build(name, repo):
    CASES[name][0](repo)
    return repo
