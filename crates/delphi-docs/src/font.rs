/// Advance of one character, in glyph pixels (5 columns and a 1-pixel gap).
pub const ADVANCE: usize = 6;
/// Rows from the top of a capital to the baseline.
pub const CAP_ROWS: usize = 7;

/// The characters that stand in for the ones the font lacks: what the charts print beyond ASCII.
fn substitute(c: char) -> &'static str {
    match c {
        '·' | '•' | '∙' => "\u{1}",
        '—' | '–' | '−' | '‑' => "-",
        '…' => "...",
        '×' => "x",
        '’' | '‘' | '′' => "'",
        '“' | '”' | '″' => "\"",
        '≤' => "<",
        '≥' | '→' | '›' => ">",
        '‹' | '←' => "<",
        '\t' => " ",
        _ => "?",
    }
}

/// The columns of one printable character; characters the font lacks are substituted or drawn as `?`.
fn columns(c: char) -> [u8; 5] {
    match c {
        ' '..='~' => ASCII[c as usize - 0x20],
        '\u{1}' => [0x00, 0x00, 0x18, 0x00, 0x00],
        _ => ASCII['?' as usize - 0x20],
    }
}

/// The glyphs to draw for `s`, with substitutions made (so the width is the count of these).
pub fn glyphs(s: &str) -> Vec<[u8; 5]> {
    let mut out = vec![];
    for c in s.chars() {
        if (' '..='~').contains(&c) {
            out.push(columns(c));
        } else {
            out.extend(substitute(c).chars().map(columns));
        }
    }
    out
}

/// Width of `s` in glyph pixels, without the trailing gap.
pub fn width(s: &str) -> usize {
    (glyphs(s).len() * ADVANCE).saturating_sub(1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_character_has_a_distinct_glyph_except_the_space() {
        let mut seen = std::collections::HashSet::new();
        for c in '!'..='~' {
            assert!(columns(c).iter().any(|b| *b != 0), "{} is blank", c);
            assert!(seen.insert(columns(c)), "{} repeats another glyph", c);
        }
        assert_eq!(columns(' '), [0; 5]);
        assert_eq!(ASCII.len(), 95);
    }

    #[test]
    fn what_the_charts_print_beyond_ascii_is_substituted_and_unknowns_are_question_marks() {
        assert_eq!(glyphs("a·b").len(), 3);
        assert_eq!(glyphs("a—b"), glyphs("a-b"));
        assert_eq!(glyphs("…").len(), 3);
        assert_eq!(glyphs("日"), glyphs("?"));
        assert_eq!(width("ab"), 11);
        assert_eq!(width(""), 0);
    }
}
