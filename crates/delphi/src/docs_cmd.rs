//! `delphi docs` and `delphi completions`: the command reference, a man page and shell completions, all generated
//! from the one `CMDS` table behind `--help`, so none of them can drift from it. Prints only; touches no workspace.

use crate::{CMDS, Cmd, ENV};

const SHELLS: &[&str] = &["bash", "zsh", "fish"];

pub fn docs(args: &[String]) -> i32 {
    match args.first().map(String::as_str) {
        Some("cli") => {
            print!("{}", cli_markdown());
            0
        }
        Some("man") => {
            print!("{}", man_page());
            0
        }
        Some("catalog") => {
            let repo = args.iter().position(|a| a == "--repo").and_then(|i| args.get(i + 1)).map(String::as_str).unwrap_or(".");
            match catalog_markdown(std::path::Path::new(repo)) {
                Ok(md) => {
                    print!("{}", md);
                    0
                }
                Err(e) => {
                    eprintln!("delphi docs catalog: {}", e);
                    2
                }
            }
        }
        _ => {
            eprintln!("usage:\n  delphi docs cli                     the command reference, as Markdown\n  delphi docs man                     the same as a man page (roff)\n  delphi docs catalog [--repo <dir>]  the built-in roles and skills, as Markdown");
            2
        }
    }
}

/// The built-in roles and skills of a checkout, read from the frontmatter of `agents/*/AGENT.md` and `skills/*/SKILL.md`.
pub fn catalog_markdown(repo: &std::path::Path) -> Result<String, String> {
    use serde_yaml::{Mapping, Value};
    let text = |m: &Mapping, k: &str| m.get(Value::String(k.into())).and_then(Value::as_str).unwrap_or("").split_whitespace().collect::<Vec<_>>().join(" ").replace('|', "/");
    let list = |m: &Mapping, k: &str| -> Vec<String> {
        m.get(Value::String(k.into())).and_then(Value::as_sequence).map(|s| s.iter().filter_map(Value::as_str).map(String::from).collect()).unwrap_or_default()
    };
    let load = |dir: &str, file: &str| -> Result<Vec<Mapping>, String> {
        let mut out = Vec::new();
        let rd = std::fs::read_dir(repo.join(dir)).map_err(|e| format!("{}: {} (run it from a checkout or pass --repo)", repo.join(dir).display(), e))?;
        for entry in rd.flatten() {
            let Ok(t) = std::fs::read_to_string(entry.path().join(file)) else { continue };
            if let Some(fm) = crate::lint::frontmatter_of(&t) {
                out.push(fm);
            }
        }
        out.sort_by_key(|m| text(m, if file == "AGENT.md" { "id" } else { "name" }));
        Ok(out)
    };
    let agents = load("agents", "AGENT.md")?;
    let skills = load("skills", "SKILL.md")?;
    let mut out = String::new();
    out.push_str("# Roles and skills\n\n");
    out.push_str("<!-- Generated by `delphi docs catalog` from agents/*/AGENT.md and skills/*/SKILL.md. Do not edit by hand: change the manifest and regenerate. -->\n\n");
    out.push_str("What a bundle can attach to. A bundle names a **host role** by its id (never a theme name); a bundle agent runs on that role with the intersection of its tools. A skill is usable by a role only when the role lists it in `authorized_skills` and the skill lists the role in `authorized_agents`.\n\n");
    out.push_str("## Roles\n\n| id | job | default tier | skills |\n| :-- | :-- | :-- | :-- |\n");
    for a in &agents {
        let sk = list(a, "authorized_skills").into_iter().map(|s| format!("`{}`", s)).collect::<Vec<_>>().join(", ");
        out.push_str(&format!("| `{}` | {} | {} | {} |\n", text(a, "id"), text(a, "role"), text(a, "default_tier"), sk));
    }
    out.push_str("\n## Skills\n\n| name | use it when | roles |\n| :-- | :-- | :-- |\n");
    for s in &skills {
        let ro = list(s, "authorized_agents").into_iter().map(|r| format!("`{}`", r)).collect::<Vec<_>>().join(", ");
        out.push_str(&format!("| `{}` | {} | {} |\n", text(s, "name"), text(s, "description"), ro));
    }
    Ok(out)
}

pub fn completions(args: &[String]) -> i32 {
    let out = match args.first().map(String::as_str) {
        Some("bash") => bash(),
        Some("zsh") => zsh(),
        Some("fish") => fish(),
        _ => {
            eprintln!("usage: delphi completions {}", SHELLS.join("|"));
            return 2;
        }
    };
    print!("{}", out);
    0
}

/// The commands that have a word after `delphi`, plus the aliases `main` also accepts.
fn named() -> Vec<&'static Cmd> {
    CMDS.iter().filter(|c| !c.name.is_empty()).collect()
}

/// Every `--flag` that appears in a command's synopsis, in order of first appearance.
fn flags_of(c: &Cmd) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for word in c.synopsis.split(|ch: char| !(ch.is_ascii_alphanumeric() || ch == '-')) {
        if word.len() > 2 && word.starts_with("--") && !out.iter().any(|f| f == word) {
            out.push(word.to_string());
        }
    }
    out
}

/// The sub-words of a command (`bundle validate`, `kb search`): the first word of each synopsis line after the command name.
fn subcommands_of(c: &Cmd) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let prefix = format!("delphi {}", c.name);
    for line in c.synopsis.lines() {
        let Some(rest) = line.trim().strip_prefix(prefix.as_str()) else { continue };
        for part in rest.split('|') {
            let w = part.trim().trim_start_matches('[').trim_start_matches('(').split(|ch: char| !(ch.is_ascii_alphanumeric() || ch == '-')).next().unwrap_or("");
            if !w.is_empty() && !w.starts_with('-') && w.chars().all(|ch| ch.is_ascii_lowercase() || ch == '-') && !out.iter().any(|s| s == w) {
                out.push(w.to_string());
            }
        }
    }
    out
}

pub fn cli_markdown() -> String {
    let mut out = String::new();
    out.push_str("# Command reference\n\n");
    out.push_str("<!-- Generated by `delphi docs cli` from the command table in crates/delphi/src/main.rs. Do not edit by hand: change the table and regenerate. -->\n\n");
    out.push_str("`delphi` with no command sets up whatever is missing and opens the console. Options that name a place work on every command that touches a workspace: `--home <dir>` (default `$DELPHI_HOME`, else `~/.delphi`) and `--workspace <name>`. `delphi help <command>` and `delphi <command> --help` print the same text as this page and never create a workspace.\n\n");
    let mut group = "";
    for c in CMDS {
        if c.group != group {
            group = c.group;
            out.push_str(&format!("## {}\n\n", group));
        }
        let title = if c.name.is_empty() { "delphi".to_string() } else { format!("delphi {}", c.name) };
        let about = c.about[..1].to_uppercase() + &c.about[1..];
        out.push_str(&format!("### `{}`\n\n{}.\n\n```\n{}\n```\n\n", title, about, c.synopsis.trim_end().trim_start_matches('\n')));
        if !c.detail.is_empty() {
            out.push_str(&format!("{}\n\n", c.detail));
        }
    }
    out.push_str("## Environment\n\n| Variable | Meaning |\n| :-- | :-- |\n");
    for (k, v) in ENV {
        out.push_str(&format!("| `{}` | {} |\n", k, v));
    }
    out.push_str("\n`delphi --version` prints the release of this program.\n");
    out
}

fn roff(s: &str) -> String {
    let escaped = s.replace('\\', "\\\\").replace('-', "\\-");
    escaped.lines().map(|l| if l.starts_with('.') || l.starts_with('\'') { format!("\\&{}", l) } else { l.to_string() }).collect::<Vec<_>>().join("\n")
}

pub fn man_page() -> String {
    let mut out = String::new();
    out.push_str(&format!(".TH DELPHI 1 \"\" \"delphi {}\" \"User Commands\"\n", env!("CARGO_PKG_VERSION")));
    out.push_str(".SH NAME\ndelphi \\- a terminal-first multi-agent working environment\n");
    out.push_str(".SH SYNOPSIS\n.B delphi\n[\\fIcommand\\fR] [\\fIoptions\\fR]\n");
    out.push_str(".SH DESCRIPTION\nWith no command, delphi sets up whatever is missing and opens the console. The options \\fB\\-\\-home\\fR \\fIdir\\fR and \\fB\\-\\-workspace\\fR \\fIname\\fR apply to every command that touches a workspace.\n");
    let mut group = "";
    for c in CMDS {
        if c.group != group {
            group = c.group;
            out.push_str(&format!(".SH {}\n", roff(&group.to_uppercase())));
        }
        let title = if c.name.is_empty() { "delphi".to_string() } else { format!("delphi {}", c.name) };
        out.push_str(&format!(".SS {}\n{}.\n.PP\n.nf\n{}\n.fi\n", roff(&title), roff(c.about), roff(c.synopsis.trim_end())));
        if !c.detail.is_empty() {
            out.push_str(&format!(".PP\n{}\n", roff(c.detail)));
        }
    }
    out.push_str(".SH ENVIRONMENT\n");
    for (k, v) in ENV {
        out.push_str(&format!(".TP\n.B {}\n{}\n", roff(k), roff(v)));
    }
    out
}

fn bash() -> String {
    let cmds = named();
    let names: Vec<&str> = cmds.iter().map(|c| c.name).chain(["narrator", "version"]).collect();
    let mut s = String::from("# bash completion for delphi: generated by `delphi completions bash`\n_delphi() {\n    local cur=\"${COMP_WORDS[COMP_CWORD]}\" cmd=\"${COMP_WORDS[1]}\"\n    if [ \"$COMP_CWORD\" -le 1 ]; then\n");
    s.push_str(&format!("        COMPREPLY=($(compgen -W \"{} --help --version\" -- \"$cur\"))\n        return\n    fi\n    case \"$cmd\" in\n", names.join(" ")));
    for c in &cmds {
        let mut words = subcommands_of(c);
        words.extend(flags_of(c));
        words.push("--help".into());
        s.push_str(&format!("        {}) COMPREPLY=($(compgen -W \"{}\" -- \"$cur\")) ;;\n", c.name, words.join(" ")));
    }
    s.push_str("    esac\n}\ncomplete -F _delphi delphi\n");
    s
}

fn zsh() -> String {
    let cmds = named();
    let mut s = String::from("#compdef delphi\n# zsh completion for delphi: generated by `delphi completions zsh`\n_delphi() {\n    local -a commands\n    commands=(\n");
    for c in &cmds {
        s.push_str(&format!("        '{}:{}'\n", c.name, c.about.replace('\'', "'\\''").replace(':', "\\:")));
    }
    s.push_str("    )\n    if (( CURRENT == 2 )); then\n        _describe 'command' commands\n        return\n    fi\n    case \"$words[2]\" in\n");
    for c in &cmds {
        let mut words = subcommands_of(c);
        words.extend(flags_of(c));
        words.push("--help".into());
        s.push_str(&format!("        {}) compadd -- {} ;;\n", c.name, words.join(" ")));
    }
    s.push_str("    esac\n}\n_delphi \"$@\"\n");
    s
}

fn fish() -> String {
    let cmds = named();
    let mut s = String::from("# fish completion for delphi: generated by `delphi completions fish`\ncomplete -c delphi -f\n");
    for c in &cmds {
        s.push_str(&format!("complete -c delphi -n '__fish_use_subcommand' -a '{}' -d '{}'\n", c.name, c.about.replace('\'', "\\'")));
    }
    for c in &cmds {
        for sub in subcommands_of(c) {
            s.push_str(&format!("complete -c delphi -n '__fish_seen_subcommand_from {}' -a '{}'\n", c.name, sub));
        }
        for f in flags_of(c) {
            s.push_str(&format!("complete -c delphi -n '__fish_seen_subcommand_from {}' -l '{}'\n", c.name, f.trim_start_matches("--")));
        }
    }
    s
}
